import re
from collections import Counter

# 1. Підготовка алфавіту (32 літери, без 'ё')
ALPHABET = "абвгдежзийклмнопрстуфхцчшщъыьэюя"
M = len(ALPHABET)  # 32
CHAR_TO_NUM = {char: idx for idx, char in enumerate(ALPHABET)}
NUM_TO_CHAR = {idx: char for idx, char in enumerate(ALPHABET)}


# 2. Функція підготовки тексту
def format_text(text):
    text = text.lower().replace('ё', 'е')
    text = re.sub(r'[^а-я]', '', text)
    return text


# 3. Функція шифрування Віженера
def encrypt_vigenere(plaintext, key):
    ciphertext = []
    r = len(key)
    for i, char in enumerate(plaintext):
        x = CHAR_TO_NUM[char]
        k = CHAR_TO_NUM[key[i % r]]
        y = (x + k) % M
        ciphertext.append(NUM_TO_CHAR[y])
    return "".join(ciphertext)


# 4. Обчислення індексу відповідності (ІВ)
def index_of_coincidence(text):
    n = len(text)
    if n <= 1:
        return 0
    freqs = Counter(text)
    # Формула: sum( N_t * (N_t - 1) ) / ( n * (n - 1) )
    ioc = sum(f * (f - 1) for f in freqs.values()) / (n * (n - 1))
    return ioc



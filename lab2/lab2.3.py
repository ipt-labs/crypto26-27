# 3. Функція дешифрування
def decrypt_vigenere(cipher, key):
    plain = []
    key_len = len(key)
    for i, char in enumerate(cipher):
        y = C2N[char]
        k = C2N[key[i % key_len]]
        x = (y - k) % M
        plain.append(N2C[x])
    return "".join(plain)



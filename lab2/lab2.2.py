def index_of_coincidence(text):
    n = len(text)
    if n <= 1: return 0
    freqs = Counter(text)
    return sum(f * (f - 1) for f in freqs.values()) / (n * (n - 1))


def calculate_average_ioc(text, r):
    # Розбиваємо текст на r блоків
    blocks = [""] * r
    for i, char in enumerate(text):
        blocks[i % r] += char

    # Рахуємо ІВ для кожного блоку і знаходимо середнє
    iocs = [index_of_coincidence(block) for block in blocks]
    return sum(iocs) / r


